  group('SlotBoundary', () {
    // Real-scale reproduction: enough unique (non-shared-vertex) triangles
    // to push the file's total archive-slot count past 32,767 - the exact
    // condition that corrupted large flattened-geometry exports before the
    // matching Python fix. Deliberately unique vertices per triangle
    // (~11 new slots each) rather than a shared grid, landing the crossing
    // at an unpredictable slot number - the same worst case a flattened
    // CAD import produces.
    SkpBuilder buildLarge(int n) {
      final builder = create();
      for (var i = 0; i < n; i++) {
        final x = i * 10.0;
        builder.addFace([(x, 0.0, 0.0), (x + 1.0, 0.0, 0.0), (x, 1.0, 0.0)]);
      }
      return builder;
    }

    test('next_slot actually crosses the 0x7FFF boundary', () {
      final builder = buildLarge(3200);
      expect(builder.debugGeometryNextSlot! > 0x7FFF, isTrue);
    });

    test('round-trips through the own reader with the exact face count', () {
      final builder = buildLarge(3200);
      final model = SkpFile.fromBuffer(builder.toBytes()).parse();
      expect(model.root.faces.length, 3200);
    });

    test('matches Python byte-for-byte across the slot boundary', () {
      final builder = buildLarge(3200);
