    test('rotation matches an equivalent explicit matrix3x3', () {
      // `rotation:` is documented as a convenience for a hand-derived
      // `matrix3x3:` via the same Rodrigues formula ([rotationMatrix3x3],
      // also exported) - build one instance each way and confirm they
      // produce byte-identical transforms, rather than re-deriving the
      // expected numbers by hand (error-prone to get the sign/row-vs-
      // column convention right independently).
      final builder = create();
      final chair = builder.addComponentDefinition('Chair', (def) {
        def.addFace(square);
      });
      const axis = (0.0, 0.0, 1.0);
      final angle = pi / 2;
      builder.addInstance(chair, name: 'ViaRotation', rotation: (axis, angle));
      builder.addInstance(chair, name: 'ViaMatrix', matrix3x3: rotationMatrix3x3(axis, angle));
      final model = SkpFile.fromBuffer(builder.toBytes()).parse();
      final byName = {for (final i in model.root.instances) i.name: i.matrix};
      final viaRotation = byName['ViaRotation']!;
      final viaMatrix = byName['ViaMatrix']!;
      for (var i = 0; i < 9; i++) {
        expect(viaRotation[i], closeTo(viaMatrix[i], 1e-12));
      }
      // Sanity check it's a genuine 90-degree turn, not an identity/no-op:
      // the X axis (1, 0, 0) should map to +/-Y, not stay along X.
      expect(viaRotation[0].abs(), lessThan(1e-9));
      expect(viaRotation[1].abs(), closeTo(1.0, 1e-9));
    });

